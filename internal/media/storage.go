// extensionForMIME mirrors the subset of python's mimetypes.guess_extension
// the media domain can produce; an unknown type yields "" so callers can apply
// their own fallback (python returns None there as well).
func extensionForMIME(mimeType string) string {
	switch strings.ToLower(strings.TrimSpace(mimeType)) {
	case "image/png":
		return ".png"
	case "image/jpeg", "image/jpg", "image/pjpeg":
		return ".jpg"
	case "image/webp":
		return ".webp"
	case "image/gif":
		return ".gif"
	case "application/octet-stream":
		return ".bin"
	}
	return ""
}

func extensionOrPNG(mimeType string) string {
	if extension := extensionForMIME(mimeType); extension != "" {
		return extension
	}
	return ".png"
}

func extensionOrJPG(mimeType string) string {
	if extension := extensionForMIME(mimeType); extension != "" {
		return extension
	}
	return ".jpg"
}

func objectKey(userID int64, taskNo string, imageIndex int, mimeType string) string {
	return fmt.Sprintf("users/%d/tasks/%s/original-%d%s", userID, taskNo, imageIndex, extensionOrPNG(mimeType))
}

func referenceObjectKey(userID int64, taskNo, mimeType string) string {
	return fmt.Sprintf("users/%d/tasks/%s/reference%s", userID, taskNo, extensionOrPNG(mimeType))
}

func previewObjectKey(userID int64, taskNo string, imageIndex int, renderMIME string) string {
	return fmt.Sprintf("users/%d/tasks/%s/preview-%d%s", userID, taskNo, imageIndex, extensionOrJPG(renderMIME))
}

// objectPath resolves an object key inside the media root and refuses keys that
// escape it. Every key in the database is generated by this package, so the
// guard is a safety net rather than a behaviour change.
func (s *Service) objectPath(key string) (string, error) {
	root := filepath.Clean(s.cfg.MediaRoot)
	trimmed := strings.TrimSpace(key)
	if trimmed == "" {
		return "", errors.New("object key is empty")
	}
	target := filepath.Join(root, filepath.FromSlash(trimmed))
	if target != root && !strings.HasPrefix(target, root+string(filepath.Separator)) {
		return "", fmt.Errorf("object key %q escapes the media root", key)
	}
	return target, nil
}

func (s *Service) writeObject(key string, content []byte) error {
	target, err := s.objectPath(key)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
		return err
	}
	return os.WriteFile(target, content, 0o644)
}

func (s *Service) readObject(key string) ([]byte, error) {
	target, err := s.objectPath(key)
	if err != nil {
		return nil, err
	}
	return os.ReadFile(target)
}

func (s *Service) deleteObject(key string) error {
	if strings.TrimSpace(key) == "" {
		return nil
	}
	target, err := s.objectPath(key)
	if err != nil {
		return err
	}
	if err := os.Remove(target); err != nil {
		if errors.Is(err, os.ErrNotExist) {
			return nil
		}
		return err
	}
	s.pruneEmptyParents(filepath.Dir(target))
	return nil
}

// pruneEmptyParents removes the directories a deleted object leaves behind,
// stopping at the media root and at the first non-empty directory.
func (s *Service) pruneEmptyParents(dir string) {
	root := filepath.Clean(s.cfg.MediaRoot)
	for dir != root && strings.HasPrefix(dir, root+string(filepath.Separator)) {
		if err := os.Remove(dir); err != nil {
			return
		}
		dir = filepath.Dir(dir)
	}
}

